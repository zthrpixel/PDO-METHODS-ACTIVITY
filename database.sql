SELECT COUNT(*) AS total_records FROM grocery_items;

SELECT category,
       COUNT(*) AS product_count,
       SUM(stock_quantity) AS total_units,
       ROUND(SUM(price_aud * stock_quantity), 2) AS inventory_value_aud
FROM grocery_items
GROUP BY category
HAVING SUM(stock_quantity) > 0
ORDER BY inventory_value_aud DESC;
